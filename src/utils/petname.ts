export function generatePetName(keyId: string): string {
	const adjIndex = Number.parseInt(keyId.slice(0, 2), 16) % IDENTITY_ADJECTIVES.length
	const nounIndex = Number.parseInt(keyId.slice(2, 4), 16) % IDENTITY_NOUNS.length
	const actionIndex = Number.parseInt(keyId.slice(4, 6), 16) % IDENTITY_ACTIONS.length
	return `${IDENTITY_ADJECTIVES[adjIndex]}${IDENTITY_NOUNS[nounIndex]}${IDENTITY_ACTIONS[actionIndex]}`
}
